/**
 * 绘制 MT 矢量图标：按 [MtIcon.viewport] 等比缩放到 [size]，用 Compose 内置 [PathParser] 解析 pathData。
 */
@Composable
fun MtVectorIcon(
    icon: MtIcon,
    modifier: Modifier = Modifier,
    size: Dp = MtSpec.BottomBarIcon,
    tint: Color = Color.Unspecified,
) {
    val color = if (tint == Color.Unspecified) LocalContentColor.current else tint
    val parsed: List<Pair<Path, Float>> = remember(icon) {
        icon.paths.mapIndexed { i, data ->
            PathParser().parsePathString(data).toPath() to (icon.alphas.getOrNull(i) ?: 1f)
        }
    }
    Canvas(modifier.size(size)) {
        val k = this.size.minDimension / icon.viewport
        withTransform({ scale(k, k, pivot = Offset.Zero) }) {
            parsed.forEach { (path, alpha) ->
                if (alpha > 0f) drawPath(path, color = color.copy(alpha = color.alpha * alpha))
            }
        }
    }
}
